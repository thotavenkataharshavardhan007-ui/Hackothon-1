public class SolarDataTypes {
    public static void main(String[] args) {
        // Declaring variables with appropriate data types
        int panelId = 101;
        double energyGenerated = 15.5; // kWh
        int numberOfPanels = 8;
        char systemStatus = 'A'; // 'A' for Active, 'I' for Inactive

        // Displaying the details
        System.out.println("Panel ID: " + panelId);
        System.out.println("Energy Generated: " + energyGenerated + " kWh");
        System.out.println("Number of Solar Panels: " + numberOfPanels);
        System.out.println("System Status: " + systemStatus);
    }
}